class OledRenderer:
    ON_COLOR = (190, 225, 255)
    OFF_COLOR = (0, 0, 0)

    def __init__(self, scale=6, fps=6, title="Karate Champ"):
        self.scale = scale
        self.fps = fps
        self.title = title
        self._pygame = None
        self._screen = None
        self._clock = None

    # ------------------------------------------------------------ drawing
    @staticmethod
    def _blit(fb, sprite, x, y):
        h, w = sprite.shape
        x0, y0 = max(x, 0), max(y, 0)
        x1, y1 = min(x + w, SCREEN_WIDTH), min(y + h, SCREEN_HEIGHT)
        if x1 <= x0 or y1 <= y0:
            return
        fb[y0:y1, x0:x1] |= sprite[y0 - y:y1 - y, x0 - x:x1 - x]

    def _draw_player(self, fb, player, is_player_1):
        table, flip_p1, flip_p2 = STATE_SPRITES[int(player.current_state)]
        name, dy = table.get(int(player.current_frame), table[0])
        sprite = SPRITES[name]
        if flip_p1 if is_player_1 else flip_p2:
            sprite = sprite[:, ::-1]
        self._blit(fb, sprite, int(player.x), SCREEN_HEIGHT - dy)

    @staticmethod
    def _draw_box_outline(fb, box):
        x, y, w, h = (int(v) for v in box)
        for xx in range(x, x + w):
            for yy in (y, y + h - 1):
                if 0 <= xx < SCREEN_WIDTH and 0 <= yy < SCREEN_HEIGHT:
                    fb[yy, xx] = 1
        for yy in range(y, y + h):
            for xx in (x, x + w - 1):
                if 0 <= xx < SCREEN_WIDTH and 0 <= yy < SCREEN_HEIGHT:
                    fb[yy, xx] = 1

    @staticmethod
    def _draw_timer(fb, value):
        text = str(int(value))
        x = 58
        top = 8 - 5 + 1  # text baseline at y=8
        for ch in text:
            for ry, row in enumerate(_DIGITS[ch]):
                for rx, bit in enumerate(row):
                    if bit == "1":
                        fb[top + ry, x + rx] = 1
            x += 4

    def draw_frame(self, player_1, player_2, timer, boxes=()):
        """Return a (64, 128) uint8 array of 0/1 pixels, same layout as the OLED."""
        fb = np.zeros((SCREEN_HEIGHT, SCREEN_WIDTH), dtype=np.uint8)

        # same order as draw_game(): player 2, player 1, health bars
        self._draw_player(fb, player_2, is_player_1=False)
        self._draw_player(fb, player_1, is_player_1=True)

        fb[0:8, 0:max(0, int(player_1.health) // 2)] = 1
        fb[0:8, 78:78 + max(0, int(player_2.health) // 2)] = 1
        self._draw_timer(fb, timer)

        for box in boxes:
            self._draw_box_outline(fb, box)
        return fb

    def to_rgb(self, fb):
        """Scale a framebuffer up to an (64*s, 128*s, 3) RGB image."""
        big = np.kron(fb, np.ones((self.scale, self.scale), dtype=np.uint8))
        rgb = np.empty(big.shape + (3,), dtype=np.uint8)
        rgb[big == 1] = self.ON_COLOR
        rgb[big == 0] = self.OFF_COLOR
        return rgb

    # ------------------------------------------------------------- window
    def show(self, fb):
        if self._pygame is None:
            import pygame  # lazy: only needed for render_mode="human"
            self._pygame = pygame
            pygame.init()
            pygame.display.set_caption(self.title)
            self._screen = pygame.display.set_mode(
                (SCREEN_WIDTH * self.scale, SCREEN_HEIGHT * self.scale)
            )
            self._clock = pygame.time.Clock()

        pg = self._pygame
        pg.event.pump()
        rgb = self.to_rgb(fb)
        surf = pg.surfarray.make_surface(rgb.swapaxes(0, 1))
        self._screen.blit(surf, (0, 0))
        pg.display.flip()
        self._clock.tick(self.fps)

    def close(self):
        if self._pygame is not None:
            self._pygame.display.quit()
            self._pygame.quit()
        self._pygame = None
        self._screen = None
        self._clock = None