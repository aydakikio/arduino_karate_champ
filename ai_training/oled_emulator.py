def _decode_xbm(w, h, data):
    """XBM -> (h, w) uint8 array of 0/1. LSB-first, rows padded to whole bytes."""
    bpr = (w + 7) // 8
    buf = np.zeros(h * bpr, dtype=np.uint8)
    n = min(len(data), h * bpr)  # pad short arrays, truncate long ones
    buf[:n] = data[:n]
    rows = buf.reshape(h, bpr)
    return np.unpackbits(rows, axis=1, bitorder="little")[:, :w].astype(np.uint8)


