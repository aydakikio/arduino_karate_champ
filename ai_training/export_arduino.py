"""
1. Round-robin league among checkpoints (greedy play, both seats) -> pick the most robust one.
2. Post-training quantisation to int8 weights / int32 accumulators (integer-only inference).
3. Validate quantised policy in the sim, dump test vectors, emit karate_ai.h for the Nano.
"""
import argparse, glob, pickle, itertools, os, re
import numpy as np
from karate_sim import *
from train_selfplay import NetAgent, Frozen, Scripted, RandomAgent, Constant, evaluate, obs_batch


def quantize(W1, b1, W2, b2):
    k1 = int(np.floor(np.log2(127.0 / np.abs(W1).max())))
    k2 = int(np.floor(np.log2(127.0 / np.abs(W2).max())))
    q = dict(
        k1=k1, k2=k2,
        W1=np.clip(np.rint(W1 * 2 ** k1), -127, 127).astype(np.int8),          # (in, hid)
        B1=np.rint(b1 * 127 * 2 ** k1).astype(np.int32),
        W2=np.clip(np.rint(W2 * 2 ** k2), -127, 127).astype(np.int8),          # (hid, out)
        B2=np.rint(b2 * 127 * 2 ** k2).astype(np.int32))
    return q


def q_forward(q, xq):
    """Exactly what the C code computes. xq: (n, 29) ints in 0..127."""
    acc1 = xq.astype(np.int64) @ q["W1"].astype(np.int64) + q["B1"]
    h = np.where(acc1 > 0, np.minimum(acc1 >> q["k1"], 32767), 0)
    acc2 = h @ q["W2"].astype(np.int64) + q["B2"]
    return acc2


class QuantAgent:
    def __init__(s, q, eps=0.0): s.q, s.eps = q, eps
    def act(s, X, fights, seats, rng):
        xq = np.rint(X * 127).astype(np.int64)
        out = q_forward(s.q, xq).argmax(1)
        if s.eps:
            m = rng.random(len(out)) < s.eps
            out = np.where(m, rng.integers(0, N_ACTIONS, len(out)), out)
        return out


def atk_top_share(agent, opp, n=48, steps=400, seed=21):
    """Share of the most-used attack type among attacks the agent actually starts (1.0 = one-move agent)."""
    rng = np.random.default_rng(seed)
    fights = [Fight(seed=seed + i) for i in range(n)]; seats = [i % 2 for i in range(n)]
    cnt = np.zeros(4)
    for _ in range(steps):
        X = obs_batch(fights, seats); a = agent.act(X, fights, seats, rng)
        o = opp.act(obs_batch(fights, [1 - s for s in seats]), fights, [1 - s for s in seats], rng)
        for i, f in enumerate(fights):
            if f.term or f.trunc: f.reset(); continue
            if not f.p[seats[i]].locked and ATTACK[a[i]]: cnt[ATK_TYPE[a[i]] - 1] += 1
            x = [0, 0]; x[seats[i]] = int(a[i]); x[1 - seats[i]] = int(o[i]); f.step(*x)
    return float(cnt.max() / max(cnt.sum(), 1)), cnt / max(cnt.sum(), 1)


def fmt(arr, per=16):
    flat = [str(int(v)) for v in np.asarray(arr).flatten()]
    return ",\n  ".join(", ".join(flat[i:i + per]) for i in range(0, len(flat), per))


HEADER = r'''/* karate_ai.h  --  generated by export_arduino.py  (do not edit by hand)
 *
 * Self-play-trained policy for Karate Champ, int8 weights, integer-only inference.
 * Network: %(IN)d inputs -> %(HID)d ReLU -> %(OUT)d actions (argmax).
 * Flash: ~%(FLASH)d bytes of PROGMEM.  RAM: ~%(RAM)d bytes of stack while running.
 *
 * Actions use the same ids as the Python env / your state ids:
 *   0 IDLE 1 WALK_BACK 2 WALK_FWD 3 PUNCH 4 FRONT_KICK 5 BACK_KICK
 *   6 BLOCK_R 7 BLOCK_L 8 SWEEP_L 9 SWEEP_R
 *
 * Call once per game tick (the env steps at 6 Hz).  RECOMMENDED: kai_choose_action_sampled(...same args..., random(0, 65536))
 *   uint8_t a = kai_choose_action(me_is_p1, p1_x, p2_x, my_hp, opp_hp,
 *                                 my_state, my_frame, opp_state, opp_frame, time_left, last_atk);
 * where
 *   me_is_p1   1 if the AI controls player 1 (left side), 0 if player 2
 *   p1_x,p2_x  the players' x positions (same coordinates as the env: P1 starts 30, P2 100,
 *              clamped to 4..110)
 *   *_hp       0..100            *_state 0..9            *_frame 0..6 (current animation frame)
 *   time_left  0..127  = round-time-left * 127 / 90 seconds  (127 at round start)
 *   last_atk   the attack type THIS fighter last started: 0 none yet, 1 punch (3), 2 front kick (4),
 *              3 back kick (5), 4 sweep (8 or 9).  Keep one uint8_t per fighter, set it whenever you
 *              accept an attack action, reset to 0 at round start.
 */
#ifndef KARATE_AI_H
#define KARATE_AI_H
#include <stdint.h>
#include <math.h>
#ifdef __AVR__
  #include <avr/pgmspace.h>
  #define KAI_RD8(p)  ((int8_t)pgm_read_byte(p))
  #define KAI_RD32(p) ((int32_t)pgm_read_dword(p))
#else
  #define PROGMEM
  #define KAI_RD8(p)  (*(p))
  #define KAI_RD32(p) (*(p))
#endif

#define KAI_IN     %(IN)d
#define KAI_HID    %(HID)d
#define KAI_OUT    %(OUT)d
#define KAI_SHIFT1 %(K1)d

static const int8_t  KAI_W1[KAI_HID * KAI_IN] PROGMEM = {
  %(W1)s
};
static const int32_t KAI_B1[KAI_HID] PROGMEM = {
  %(B1)s
};
static const int8_t  KAI_W2[KAI_OUT * KAI_HID] PROGMEM = {
  %(W2)s
};
static const int32_t KAI_B2[KAI_OUT] PROGMEM = {
  %(B2)s
};

#define KAI_TEMP 1.0f   /* sampling temperature: lower = greedier/more predictable, higher = more random */
#define KAI_LOGIT_SCALE (1.0f / (127.0f * %(P2)d.0f))   /* int logit -> real logit */

/* x[]: the 33 integer features (see karate_sim.py). Fills lg[] with integer logits. */
static inline void kai_logits(const int8_t *x, int32_t *lg)
{
    int16_t h[KAI_HID];
    for (uint8_t j = 0; j < KAI_HID; j++) {
        int32_t acc = KAI_RD32(&KAI_B1[j]);
        const int8_t *w = KAI_W1 + (uint16_t)j * KAI_IN;
        for (uint8_t i = 0; i < KAI_IN; i++) {
            int8_t xi = x[i];
            if (xi) acc += (int16_t)KAI_RD8(&w[i]) * xi;
        }
        if (acc <= 0) { h[j] = 0; }
        else { acc >>= KAI_SHIFT1; h[j] = (acc > 32767) ? 32767 : (int16_t)acc; }
    }
    for (uint8_t o = 0; o < KAI_OUT; o++) {
        int32_t acc = KAI_RD32(&KAI_B2[o]);
        const int8_t *w = KAI_W2 + (uint16_t)o * KAI_HID;
        for (uint8_t j = 0; j < KAI_HID; j++)
            acc += (int32_t)KAI_RD8(&w[j]) * h[j];
        lg[o] = acc;
    }
}

static inline uint8_t kai_argmax(const int32_t *lg)
{
    uint8_t best = 0;
    for (uint8_t o = 1; o < KAI_OUT; o++) if (lg[o] > lg[best]) best = o;
    return best;
}

/* softmax sample; rnd = any uniform 16-bit random number (e.g. random(0, 65536)) */
static inline uint8_t kai_sample(const int32_t *lg, uint16_t rnd)
{
    int32_t mx = lg[kai_argmax(lg)];
    float w[KAI_OUT], sum = 0.0f;
    for (uint8_t o = 0; o < KAI_OUT; o++) {
        w[o] = (float)exp((double)((float)(lg[o] - mx) * (KAI_LOGIT_SCALE / KAI_TEMP)));
        sum += w[o];
    }
    float r = ((float)rnd / 65536.0f) * sum, acc = 0.0f;
    for (uint8_t o = 0; o < KAI_OUT; o++) { acc += w[o]; if (r < acc) return o; }
    return KAI_OUT - 1;
}

static inline int16_t kai_clamp(int16_t v, int16_t lo, int16_t hi) { return v < lo ? lo : (v > hi ? hi : v); }

static inline uint8_t kai_locked(uint8_t s) { return s == 3 || s == 4 || s == 5 || s == 8 || s == 9; }

static inline void kai_features(int8_t *x, uint8_t me_is_p1, int16_t p1_x, int16_t p2_x,
                                uint8_t my_hp, uint8_t opp_hp, uint8_t my_state, uint8_t my_frame,
                                uint8_t opp_state, uint8_t opp_frame, uint8_t time_left, uint8_t last_atk)
{
    for (uint8_t i = 0; i < KAI_IN; i++) x[i] = 0;
    int16_t mw, ow;
    if (me_is_p1) { mw = p1_x - 4;   ow = 110 - p2_x; }
    else          { mw = 110 - p2_x; ow = p1_x - 4;   }
    x[0] = (int8_t)kai_clamp(my_hp, 0, 100);
    x[1] = (int8_t)kai_clamp(opp_hp, 0, 100);
    x[2] = (int8_t)kai_clamp(p2_x - p1_x, 0, 127);
    x[3] = (int8_t)kai_clamp(mw, 0, 127);
    x[4] = (int8_t)kai_clamp(ow, 0, 127);
    x[5] = (int8_t)(kai_clamp(my_frame, 0, 6) * 20);
    x[6] = (int8_t)(kai_clamp(opp_frame, 0, 6) * 20);
    x[7] = (int8_t)kai_clamp(time_left, 0, 127);
    x[8] = me_is_p1 ? 127 : 0;
    if (my_state < 10)  x[9 + my_state]   = 127;
    if (opp_state < 10) x[19 + opp_state] = 127;
    if (last_atk >= 1 && last_atk <= 4) x[28 + last_atk] = 127;
}

/* Deterministic (argmax).  WARNING: predictable -> exploitable.  Prefer kai_choose_action_sampled(). */
static inline uint8_t kai_choose_action(uint8_t me_is_p1, int16_t p1_x, int16_t p2_x,
                                        uint8_t my_hp, uint8_t opp_hp,
                                        uint8_t my_state, uint8_t my_frame,
                                        uint8_t opp_state, uint8_t opp_frame,
                                        uint8_t time_left, uint8_t last_atk)
{
    if (kai_locked(my_state)) return my_state;   /* inside an attack animation: input is ignored */
    int8_t x[KAI_IN]; int32_t lg[KAI_OUT];
    kai_features(x, me_is_p1, p1_x, p2_x, my_hp, opp_hp, my_state, my_frame, opp_state, opp_frame, time_left, last_atk);
    kai_logits(x, lg);
    return kai_argmax(lg);
}

/* Recommended: same inputs + a 16-bit random number; samples from the policy. */
static inline uint8_t kai_choose_action_sampled(uint8_t me_is_p1, int16_t p1_x, int16_t p2_x,
                                        uint8_t my_hp, uint8_t opp_hp,
                                        uint8_t my_state, uint8_t my_frame,
                                        uint8_t opp_state, uint8_t opp_frame,
                                        uint8_t time_left, uint8_t last_atk, uint16_t rnd)
{
    if (kai_locked(my_state)) return my_state;
    int8_t x[KAI_IN]; int32_t lg[KAI_OUT];
    kai_features(x, me_is_p1, p1_x, p2_x, my_hp, opp_hp, my_state, my_frame, opp_state, opp_frame, time_left, last_atk);
    kai_logits(x, lg);
    return kai_sample(lg, rnd);
}
#endif
'''


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--run", default="run_main")
    ap.add_argument("--pick", default=None, help="force a checkpoint file instead of league selection")
    ap.add_argument("--out", default="export")
    a = ap.parse_args()
    os.makedirs(a.out, exist_ok=True)
    scripted = Scripted()

    # ---------------- 1. league selection
    def it_of(c): return int(re.findall(r"(\d+)", os.path.basename(c))[0])
    ck = [c for c in sorted(glob.glob(f"{a.run}/ckpt_*.pkl")) if it_of(c) >= 400 and it_of(c) % 100 == 0]
    snaps = {os.path.basename(c): pickle.load(open(c, "rb")) for c in ck}
    EPS = 0.05  # 5% random actions in evaluation so deterministic nets don't just replay one game
    ag = {k: NetAgent(Frozen(v), greedy=True, eps=EPS) for k, v in snaps.items()}
    names = list(ag)
    score = {k: [] for k in names}; ko = {k: [] for k in names}
    for i, j in itertools.combinations(names, 2):
        s, k_ = evaluate(ag[i], ag[j], n=48, seed=7, full=True)
        score[i].append(s); score[j].append(1 - s); ko[i].append(k_); ko[j].append(k_)
    rows = []
    for k in names:
        bots = [evaluate(ag[k], o, n=48, seed=9) for o in (scripted, RandomAgent(), Constant(IDLE), Constant(WALK_FWD))]
        top, _ = atk_top_share(NetAgent(Frozen(snaps[k]), greedy=True, eps=0.0), scripted)
        rows.append(dict(name=k, league=float(np.mean(score[k])), ko=float(np.mean(ko[k])), bots=min(bots), top=top))
    print("checkpoint        league-score  KO-rate-vs-peers  worst-bot-score  top-attack-share")
    for r in rows: print(f"  {r['name']}   {r['league']:.3f}        {r['ko']:.2f}             {r['bots']:.2f}             {r['top']:.2f}")
    ok = [r for r in rows if r["bots"] >= 0.95 and r["ko"] >= 0.6 and r["top"] <= 0.60]
    best = a.pick or max(ok or rows, key=lambda r: r["league"])["name"]
    print("selected:", best)
    W1, W2 = snaps[best][0]; b1, b2 = snaps[best][1]
    # ---------------- 2. quantise & validate
    q = quantize(W1, b1, W2, b2)
    fl, qa = ag[best], QuantAgent(q, eps=EPS)
    print(f"shift1={q['k1']} shift2={q['k2']}  max|W1q|={np.abs(q['W1']).max()} max|W2q|={np.abs(q['W2']).max()}")

    # collect real game states (float agent vs mixed opponents) to measure action agreement + make test vectors
    rng = np.random.default_rng(3)
    states, agree, tot = [], 0, 0
    for opp in [fl, scripted, RandomAgent(), NetAgent(Frozen(snaps[names[0]]), greedy=True)]:
        fights = [Fight(seed=500 + i) for i in range(32)]; seats = [i % 2 for i in range(32)]
        for t in range(220):
            X = obs_batch(fights, seats)
            af = NetAgent(fl.net, greedy=True).act(X, fights, seats, rng); aq = QuantAgent(q).act(X, fights, seats, rng)
            for i, f in enumerate(fights):
                me = f.p[seats[i]]
                if not ATTACK[me.st]:          # locked states are irrelevant (action ignored)
                    tot += 1; agree += int(af[i] == aq[i])
                    op = f.p[1 - seats[i]]
                    states.append((1 - seats[i], f.p[0].x, f.p[1].x, me.hp, op.hp, me.st, me.fr, op.st, op.fr,
                                   (f.max_steps - f.steps) * 127 // f.max_steps, me.last, int(aq[i])))
            Xo = obs_batch(fights, [1 - s for s in seats])
            ao = opp.act(Xo, fights, [1 - s for s in seats], rng)
            for i, f in enumerate(fights):
                if f.term or f.trunc: f.reset(); continue
                a12 = [0, 0]; a12[seats[i]] = int(af[i]); a12[1 - seats[i]] = int(ao[i]); f.step(*a12)
    print(f"action agreement float vs int8 on {tot} real states: {agree / tot:.4f}")
    for name, opp in [("float net", fl), ("scripted P1", scripted), ("random", RandomAgent()),
                      ("idle", Constant(IDLE)), ("block", Constant(BLOCK_R)), ("walk-fwd", Constant(WALK_FWD))]:
        print(f"  int8 net vs {name:12s}: score {evaluate(qa, opp, n=128, seed=11):.3f}")

    # ---------------- 3. emit header + vectors
    IN, HID = q["W1"].shape; OUT = q["W2"].shape[1]
    flash = IN * HID + HID * OUT + 4 * (HID + OUT)
    hdr = HEADER % dict(IN=IN, HID=HID, OUT=OUT, K1=q["k1"], FLASH=flash, RAM=HID * 2 + IN + 16,
                        P2=2 ** q["k2"], W1=fmt(q["W1"].T), B1=fmt(q["B1"], 8), W2=fmt(q["W2"].T), B2=fmt(q["B2"], 8))
    open(f"{a.out}/karate_ai.h", "w").write(hdr)
    np.savez(f"{a.out}/policy_float.npz", W1=W1, b1=b1, W2=W2, b2=b2)
    np.savez(f"{a.out}/policy_int8.npz", **q)
    sel = states[:: max(1, len(states) // 4000)]
    rnd = np.random.default_rng(1)
    for _ in range(1500):  # plus fuzzed states incl. out-of-range-ish values the game could produce
        st_me = int(rnd.integers(0, 10))
        if ATTACK[st_me]: continue
        sel.append((int(rnd.integers(0, 2)), int(rnd.integers(4, 111)), int(rnd.integers(4, 111)),
                    int(rnd.integers(0, 101)), int(rnd.integers(0, 101)), st_me, int(rnd.integers(0, ANIM_LEN[st_me])),
                    int(rnd.integers(0, 10)), int(rnd.integers(0, 7)), int(rnd.integers(0, 128)), int(rnd.integers(0, 5)), -1))
    out = []
    for (mip1, x1, x2, mh, oh, ms, mf, os_, of, tl, la, _) in sel:
        v = [0] * N_FEATURES
        mip1 = 1 - mip1 if False else mip1
        v[0], v[1] = mh, oh; v[2] = min(127, max(0, x2 - x1))
        v[3], v[4] = ((x1 - 4, 110 - x2) if mip1 else (110 - x2, x1 - 4))
        v[3], v[4] = min(127, max(0, v[3])), min(127, max(0, v[4]))
        v[5], v[6], v[7], v[8] = mf * 20, of * 20, tl, 127 if mip1 else 0
        v[9 + ms] = 127; v[19 + os_] = 127
        if la: v[28 + la] = 127
        exp = int(q_forward(q, np.array([v]))[0].argmax())
        out.append((mip1, x1, x2, mh, oh, ms, mf, os_, of, tl, la, exp))
    np.savetxt(f"{a.out}/test_vectors.csv", np.array(out), fmt="%d", delimiter=",")
    srows = []
    for row in out[:200]:
        mip1, x1, x2, mh, oh, ms, mf, os_, of, tl, la, _ = row
        v = [0] * N_FEATURES
        v[0], v[1] = mh, oh; v[2] = min(127, max(0, x2 - x1))
        v[3], v[4] = ((x1 - 4, 110 - x2) if mip1 else (110 - x2, x1 - 4)); v[3], v[4] = min(127, max(0, v[3])), min(127, max(0, v[4]))
        v[5], v[6], v[7], v[8] = mf * 20, of * 20, tl, 127 if mip1 else 0
        v[9 + ms] = 127; v[19 + os_] = 127
        if la: v[28 + la] = 127
        lg = q_forward(q, np.array([v]))[0].astype(np.float32)
        for rnd in (0, 3000, 12000, 25000, 33000, 45000, 60000, 65535):
            w = np.exp((lg - lg.max()) * np.float32(1.0 / (127 * 2 ** q["k2"]))); r = np.float32(rnd / 65536.0) * w.sum()
            srows.append(tuple(row[:11]) + (rnd, int(np.argmax(r < np.cumsum(w)))))
    np.savetxt(f"{a.out}/test_vectors_sampled.csv", np.array(srows), fmt="%d", delimiter=",")
    print(f"wrote {a.out}/karate_ai.h  ({flash} B flash for weights), {len(out)} test vectors")

if __name__ == "__main__":
    main()